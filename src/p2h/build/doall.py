"""Running a contest package's build scripts (``doall``).

The scripts are generated by Polygon and live inside the untrusted contest zip,
so this module keeps three promises:

1. **Never block.** Polygon's scripts call ``read``/``pause`` when something
   fails. stdin is always redirected to ``DEVNULL`` so a broken script fails
   instead of waiting for a keypress forever.
2. **Never take the whole contest down.** A failing problem is recorded and the
   remaining problems still get converted.
3. **Pick the host's entry point.** See :mod:`p2h.build.platform`.
"""

from __future__ import annotations

import os
import re
import shlex
import shutil
import subprocess
import sys
from pathlib import Path

from p2h import kinds
from p2h.build import crossrun
from p2h.build.platform import doall_command, doall_script_kind


def precheck_doall(work_root: Path, slugs: list[str], policy: str) -> str | None:
    """Warn about (or refuse) missing tools before running any script.

    Returns an error message when the caller must abort, otherwise ``None``.
    This is a static scan of the scripts, so it can only be a hint: a tool may
    still resolve through a wrapper the scan cannot see.
    """
    missing = detect_missing_tools(work_root, slugs)
    if not missing:
        return None

    message = (
        "missing environment tools for doall (precheck warning): "
        f"{', '.join(missing)}; doall may still work in special environments"
    )
    if policy == "error":
        return message + "; abort due to --missing-env error"

    print(f"warning: {message}", file=sys.stderr)
    if policy == "ask" and not confirm_continue_after_missing_env(missing):
        return "user aborted after missing environment warning"
    return None


def confirm_continue_after_missing_env(missing_tools: list[str]) -> bool:
    prompt = (
        "missing environment precheck warning for doall: "
        f"{', '.join(missing_tools)}. Continue anyway? [y/N]: "
    )
    try:
        answer = input(prompt).strip().lower()
    except EOFError:
        return False
    return answer in {"y", "yes"}


def detect_missing_tools(work_root: Path, slugs: list[str]) -> list[str]:
    """Names of the tools the scripts for ``slugs`` need but this host lacks."""
    tools: set[str] = set()

    for slug in slugs:
        problem_root = work_root / "problems" / slug
        kind = doall_script_kind(problem_root)
        if kind is None:
            continue

        shell_script = kind == ".sh"
        _collect_tools_from_script(problem_root / f"doall{kind}", tools, generic_tokens=shell_script)

        scripts_dir = problem_root / "scripts"
        if scripts_dir.exists():
            for path in scripts_dir.rglob(f"*{kind}"):
                if path.is_file():
                    _collect_tools_from_script(path, tools, generic_tokens=shell_script)

    return [tool for tool in sorted(tools) if shutil.which(tool) is None]


def run_doall_for_all(
    work_root: Path,
    slugs: list[str],
    *,
    verbose: bool,
    interactive_runner: str = "auto",
) -> dict[str, str]:
    """Run each problem's build script, returning ``{slug: error}`` for failures.

    ``interactive_runner`` decides what happens to interactive problems:

    ``auto``     run the package's own script, fall back to CrossRun on failure
    ``package``  only ever run the package's own script
    ``crossrun`` skip the package script and use CrossRun when available
    """
    failures: dict[str, str] = {}
    for slug in slugs:
        problem_root = work_root / "problems" / slug
        needs_interactor = kinds.detect_from_dir(problem_root).answer_source == "interactor"

        if interactive_runner == "crossrun" and needs_interactor and crossrun.is_applicable(problem_root):
            error = _crossrun_answers(problem_root, slug, verbose=verbose)
            if error is not None:
                failures[slug] = error
                print(f"warning: doall failed for {slug}: {error}", file=sys.stderr)
            continue

        command = doall_command(problem_root)
        if command is None:
            if verbose:
                print(f"[{slug}] skip doall (no doall.sh/doall.bat)")
            continue

        make_scripts_executable(problem_root)

        if verbose:
            print(f"[{slug}] running {' '.join(command)}")
        result = subprocess.run(
            command,
            cwd=problem_root,
            env=_doall_env(),
            stdin=subprocess.DEVNULL,
            capture_output=True,
            text=True,
            errors="replace",
        )
        if verbose and result.stdout:
            print(result.stdout, end="")
        if result.returncode != 0:
            tail = _error_tail(result)
            if interactive_runner != "package" and needs_interactor:
                recovered = _crossrun_answers(problem_root, slug, verbose=verbose)
                if recovered is None:
                    continue
                tail = f"{tail}; {recovered}"
            failures[slug] = tail
            print(f"warning: doall failed for {slug}: {tail}", file=sys.stderr)
            continue
        if verbose:
            print(f"[{slug}] doall done")
    return failures


def _crossrun_answers(problem_root: Path, slug: str, *, verbose: bool) -> str | None:
    """Rebuild answers with CrossRun. Returns ``None`` on success, else why not."""
    errors = crossrun.generate_answers(problem_root, verbose=verbose)
    if errors is None:
        return "CrossRun is not usable for this problem (missing jar, java, or binaries)"
    if errors:
        test, detail = next(iter(errors.items()))
        return f"crossrun failed for {len(errors)} test(s), e.g. {test}: {detail}"
    print(f"info: rebuilt answers for {slug} via CrossRun", file=sys.stderr)
    return None


def make_scripts_executable(problem_root: Path) -> None:
    """Set the executable bit on everything a POSIX doall may invoke.

    A no-op on Windows, where the bit does not exist and the scripts are started
    through an explicit interpreter anyway.
    """
    for path in _executable_candidates(problem_root):
        path.chmod(path.stat().st_mode | 0o111)


def _executable_candidates(problem_root: Path):
    doall_sh = problem_root / "doall.sh"
    if doall_sh.exists():
        yield doall_sh

    scripts_dir = problem_root / "scripts"
    if scripts_dir.exists():
        for path in scripts_dir.rglob("*.sh"):
            if path.is_file():
                yield path

    for directory, suffixes in (
        (problem_root / "files", {".exe", ""}),
        (problem_root / "solutions", {".exe", ""}),
    ):
        if directory.exists():
            for path in directory.iterdir():
                if path.is_file() and path.suffix in suffixes:
                    yield path

    checker = problem_root / "check.exe"
    if checker.exists():
        yield checker

    for extra in (problem_root / "statements", problem_root / "statement-sections"):
        if extra.exists():
            for path in extra.rglob("*.sh"):
                if path.is_file():
                    yield path


def _doall_env() -> dict[str, str]:
    env = os.environ.copy()
    env.setdefault("PATH", "/usr/bin:/bin:/usr/local/bin")
    return env


def _error_tail(result: subprocess.CompletedProcess[str]) -> str:
    lines = [line.strip() for line in (result.stderr or result.stdout or "").splitlines() if line.strip()]
    return "; ".join(lines[-3:]) if lines else f"exit code {result.returncode}"


_SHELL_KEYWORDS = {
    "if", "then", "fi", "for", "do", "done", "case", "esac", "while", "until",
    "function", "local", "export", "unset", "readonly", "eval", "echo", "read",
    "rm", "mv", "cp", "mkdir", "cd", "test", "true", "false", "exit", "return",
    "set", "shift", "source", ".", "in",
}


def _collect_tools_from_script(script_path: Path, tools: set[str], *, generic_tokens: bool = True) -> None:
    """Collect the external tools one doall script needs.

    ``generic_tokens`` only makes sense for POSIX shell. A ``.bat`` file's first
    token is a cmd builtin (``call``/``set``/``echo``/...) and the binaries it
    runs are relative paths inside the package, so treating those as PATH
    lookups would report tools that were never needed.
    """
    if not script_path.exists() or not script_path.is_file():
        return

    text = script_path.read_text(encoding="utf-8", errors="ignore")
    for line in text.splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue

        if re.match(r"^[A-Za-z_][A-Za-z0-9_]*\s*=", stripped):
            continue
        if re.match(r"^[A-Za-z_][A-Za-z0-9_]*\s*\(\)\s*\{?", stripped):
            continue

        if re.search(r"(^|\s)wine\s", stripped):
            tools.add("wine")
        if re.search(r"(^|\s)java\s", stripped):
            tools.add("java")
        if re.search(r"(^|\s)javac\s", stripped):
            tools.add("javac")

        if not generic_tokens:
            continue

        try:
            first = shlex.split(stripped, posix=True)[0]
        except Exception:
            continue

        if first in _SHELL_KEYWORDS or first in {"bash", "sh"}:
            continue
        if first.startswith(("scripts/", "$", "./", "../")):
            continue

        tools.add(first)
